// Feed a document that did NOT come from Google Drive into Company Brain.
//
// WHY THIS FILE EXISTS. Every other path into brain_files goes through
// upsertExtractedFile() in store.mjs, which is built entirely around a real
// Drive file (extracted.fileId, extracted.webViewLink, needsTranscription,
// needsOcr — all Drive concepts). That is correct for what it does and this
// file does not touch it, does not import it, and does not change it.
//
// Chris asked (2026-09-07) for the AI agent that manages the company —
// Company Brain, the thing this whole module implements — to be able to see
// the new marketing-analytics data (ad performance, funnel pages, VSL watch
// time) and produce weekly briefs. That data has no Drive file behind it. It
// is generated by this app, from this app's own database.
//
// brain_files.drive_file_id is just a UNIQUE TEXT key — nothing validates it
// against a real Google Drive id, and nothing in retrieve.mjs or answer.mjs
// cares where a chunk's source file came from. So a synthetic, stable key
// (see driveFileIdFor below) is a legitimate, low-risk way to make a
// generated document a first-class citizen of brain_files/brain_chunks,
// reusing replaceFileChunks() — already exported, already does the real
// work (chunk, embed, store) — rather than re-implementing any of it.
//
// ACCESS TIER. Everything ingested here defaults to 'owner'. A weekly brief
// or a raw performance number is exactly the kind of thing
// docs/ops/2026-09-06-self-analysis.md already treats as owner-only
// information, matching the fail-closed default upsertExtractedFile() itself
// uses for an unclassified Drive file.

import crypto from "node:crypto";
import { replaceFileChunks } from "./store.mjs";

/** A stable, collision-free key for a generated (non-Drive) document.
 *  Same sourceType + sourceKey always resolves to the same brain_files row,
 *  so re-running a weekly brief for the same week UPDATES that week's
 *  document rather than piling up duplicates. */
export function driveFileIdFor(sourceType, sourceKey) {
  const clean = (s) => String(s || "").trim().toLowerCase().replace(/[^a-z0-9_-]+/g, "-");
  return `generated:${clean(sourceType)}:${clean(sourceKey)}`;
}

/**
 * upsertGeneratedDocument(db, { orgId, sourceType, sourceKey, title, text,
 *   accessTier, env, fetchImpl, embed })
 * → { ok, fileId, chunkCount, reason? }
 *
 * sourceType — a short label for what kind of thing this is, e.g.
 *   "weekly-ops-brief", "ad-performance-summary". Shows up in citations.
 * sourceKey  — what makes THIS one unique within its sourceType, e.g. an
 *   ISO week string. Together with sourceType it is the whole identity of
 *   the row (see driveFileIdFor) — get this wrong and either two different
 *   documents collide into one, or the same document duplicates every run.
 */
export async function upsertGeneratedDocument(db, {
  orgId,
  sourceType,
  sourceKey,
  title,
  text,
  accessTier = "owner",
  env = process.env,
  fetchImpl,
  embed
} = {}) {
  if (!orgId) return { ok: false, reason: "org_id_required" };
  if (!sourceType || !sourceKey) return { ok: false, reason: "source_type_and_key_required" };
  const body = String(text || "").trim();
  if (!body) return { ok: false, reason: "no_text" };

  const driveFileId = driveFileIdFor(sourceType, sourceKey);
  const contentHash = crypto.createHash("sha256").update(body, "utf8").digest("hex");

  const existing = await db.query(
    `SELECT id, content_sha256 FROM brain_files WHERE org_id = $1 AND drive_file_id = $2`,
    [orgId, driveFileId]
  );
  const prior = existing.rows?.[0];

  // Same content as last time — do not re-embed (embedding calls cost money
  // and this can be re-run any number of times, e.g. by a retry).
  if (prior && prior.content_sha256 === contentHash) {
    return { ok: true, fileId: prior.id, chunkCount: 0, skipped: true, reason: "unchanged" };
  }

  let fileId;
  if (prior) {
    await db.query(
      `UPDATE brain_files SET
         name = $2, mime_type = 'text/plain', access_tier = $3,
         content_sha256 = $4, indexed_at = now(), updated_at = now()
       WHERE id = $1`,
      [prior.id, title || sourceType, accessTier, contentHash]
    );
    fileId = prior.id;
  } else {
    // source='generated' — see 303_company_brain_generated_source.sql.
    // approval_status is left at its schema default ('approved') on purpose:
    // a system-generated brief does not sit in the same manual-review queue
    // a staff upload does.
    const inserted = await db.query(
      `INSERT INTO brain_files
         (org_id, drive_file_id, name, mime_type, access_tier, unattached, content_sha256, indexed_at, source)
       VALUES ($1, $2, $3, 'text/plain', $4, true, $5, now(), 'generated')
       RETURNING id`,
      [orgId, driveFileId, title || sourceType, accessTier, contentHash]
    );
    fileId = inserted.rows[0].id;
  }

  const result = await replaceFileChunks(db, { orgId, fileId, text: body, accessTier, env, fetchImpl, embed });
  if (!result.ok) return { ok: false, fileId, reason: result.reason };

  return { ok: true, fileId, chunkCount: result.chunkCount, skipped: false };
}
