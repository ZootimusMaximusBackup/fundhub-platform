// Regenerates db/expected-migrations.mjs from what db/ actually holds.
//
// The list has to be a checked-in module, not an fs walk at request time: the
// health endpoint runs inside the esbuild-bundled Netlify function, where the
// db/*.sql files are not present. A module gets bundled with the code, so the
// deployed function knows which migrations that code expects.
//
// Usage: npm run migrations:manifest
//
// src/http/health-migrations.test.mjs fails if the checked-in list and db/ differ,
// so a new migration cannot land without this being re-run.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DB = path.join(HERE, "..", "..", "db");
const OUT = path.join(DB, "expected-migrations.mjs");

// The same walk, in the same order, as db/migrate.mjs.
const keys = [];
for (const d of ["schema", "migrations", "seed"]) {
  const dir = path.join(DB, d);
  if (!fs.existsSync(dir)) continue;
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".sql")).sort()) {
    keys.push(`${d}/${f}`);
  }
}

const header = `// GENERATED by scripts/db/expected-migrations.mjs — do not edit by hand.
//
// Every migration key this build of the code expects to find in the database's
// schema_migrations table, in the order db/migrate.mjs applies them. src/http/health.mjs
// compares the applied keys against this list so a deploy that ran no migrations
// reports "behind" instead of "up".
//
// Re-run \`npm run migrations:manifest\` after adding a .sql file under db/.

export const EXPECTED_MIGRATIONS = Object.freeze([
`;

fs.writeFileSync(OUT, header + keys.map((k) => `  "${k}"`).join(",\n") + "\n]);\n\nexport default EXPECTED_MIGRATIONS;\n");
console.log(`wrote ${path.relative(process.cwd(), OUT)} — ${keys.length} migration(s)`);
