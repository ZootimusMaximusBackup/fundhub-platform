-- ---------------------------------------------------------------------------
-- Grants for the unprivileged application role (104_app_role.sql).
--
-- 104 sets ALTER DEFAULT PRIVILEGES so future tables are granted automatically,
-- but that only applies to objects created by the role that set it. Migrations
-- may be applied by a different owner (MIGRATION_DATABASE_URL), so these are
-- explicit rather than assumed. Guarded, because a database that has never run
-- 104 — a throwaway CI container — has no such role and must not fail here.
--
-- DELETE is granted for consistency with every other table and is inert: both
-- tables block DELETE with a trigger above, which a GRANT cannot override.
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'fundhub_app') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON contract_templates TO fundhub_app;
    GRANT SELECT, INSERT, UPDATE, DELETE ON contracts TO fundhub_app;
  ELSE
    RAISE NOTICE 'skipped grants: role fundhub_app does not exist in this database';
  END IF;
END $$;

COMMENT ON TABLE contract_templates IS
  'Reusable contract copy with {{merge tags}}, edited from the CRM. Changing wording never needs code.';
COMMENT ON TABLE contracts IS
  'One contract sent to one client. rendered_body is frozen at send; document_versions.checksum is what proves it.';
COMMENT ON COLUMN contracts.body_sha IS
  'sha256 of rendered_body at send. The tamper check compares a fresh hash of rendered_body against document_versions.checksum — see docs/CONTRACTS-SPEC.md section 3.';
